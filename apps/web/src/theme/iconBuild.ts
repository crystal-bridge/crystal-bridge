import type { IconSource } from './iconSources.js';

/** One icon as the app draws it: a viewBox and filled paths. */
export interface IconDrawing {
  viewBox: string;
  paths: string[];
}

/** The parts of an Iconify JSON pack (`@iconify-json/*`'s `icons.json`) the build reads. */
export interface IconifyPack {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
  aliases?: Record<string, { parent: string }>;
}

const PATH = /<path fill="currentColor" d="([^"]+)"\s*\/>/g;

/**
 * An icon's drawing from its pack. Only bodies made of plain filled paths are accepted, so the app can draw every icon
 * the same way; anything else (strokes, opacity, groups) is refused with the icon's name.
 */
export function drawing(pack: IconifyPack, source: IconSource): IconDrawing {
  const name = pack.aliases?.[source.icon]?.parent ?? source.icon;
  const icon = pack.icons[name];
  if (!icon) throw new Error(`${source.pack} has no icon "${source.icon}"`);
  const paths = [...icon.body.matchAll(PATH)].map((m) => m[1]!);
  if (paths.length === 0 || icon.body.replace(PATH, '').trim() !== '') {
    throw new Error(`${source.pack}/${source.icon} isn't plain filled paths`);
  }
  const width = icon.width ?? pack.width ?? 16;
  const height = icon.height ?? pack.height ?? 16;
  return { viewBox: `0 0 ${width} ${height}`, paths };
}

/** The generated module's text. */
export function iconModule(drawings: Record<string, IconDrawing>): string {
  return [
    '// Generated by `pnpm icons` from theme/iconSources.ts and the Iconify packs it names. Do not edit.',
    "import type { IconName } from './iconSources.js';",
    "import type { IconDrawing } from './iconBuild.js';",
    '',
    `export const ICON_DATA: Record<IconName, IconDrawing> = ${JSON.stringify(drawings, null, 2)};`,
    '',
  ].join('\n');
}
