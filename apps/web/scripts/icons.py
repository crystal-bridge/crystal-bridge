#!/usr/bin/env python3
"""Generates Crystal Bridge's icons from one 16x16 pixel map: the favicon (SVG) and app icons (PNG).

Run from anywhere: python3 apps/web/scripts/icons.py. Pure Python (zlib only), so it needs no image libraries.
The crystal is original pixel art; '.' is transparent.
"""
import struct
import zlib
from pathlib import Path

ART = """
.......DD.......
......DWLD......
.....DWLLMD.....
....DWLLLMMD..*.
....DWLLLMSD.*+*
...DWLLLLMMSD.*.
...DWLLLLMSSD...
...DLLLLMMSSD...
...DMMMMSSSSD...
....DMMMSSSD....
....DMMSSSSD....
.....DMSSSD.....
.....DMSSSD.....
......DSSD......
.......DD.......
................
""".strip().splitlines()

PALETTE = {
    'D': '#1e1b4b',  # outline, deep indigo
    'W': '#f0f9ff',  # highlight edge
    'L': '#7dd3fc',  # lit facet
    'M': '#38bdf8',  # mid facet
    'S': '#0369a1',  # shadow facet
    '*': '#a5f3fc',  # sparkle arms
    '+': '#ffffff',  # sparkle core
}
BACKGROUND = '#0b1020'  # app icons sit on a dark tile, like the app itself
PUBLIC = Path(__file__).resolve().parent.parent / 'public'


def rgb(color: str) -> tuple[int, int, int]:
    return tuple(int(color[i : i + 2], 16) for i in (1, 3, 5))


def favicon() -> str:
    rects = []
    for y, row in enumerate(ART):
        x = 0
        while x < 16:
            c = row[x]
            if c == '.':
                x += 1
                continue
            run = 1
            while x + run < 16 and row[x + run] == c:
                run += 1
            rects.append(f'<rect x="{x}" y="{y}" width="{run}" height="1" fill="{PALETTE[c]}"/>')
            x += run
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">\n'
        '  <!-- Crystal Bridge: original pixel-art crystal, generated by apps/web/scripts/icons.py -->\n  '
        + '\n  '.join(rects)
        + '\n</svg>\n'
    )


def png(size: int) -> bytes:
    """The crystal centred on a dark square, scaled by whole pixels so it stays crisp, with a safe margin."""
    scale = int(size * 0.75) // 16
    offset = (size - 16 * scale) // 2
    bg = rgb(BACKGROUND)
    rows = []
    for y in range(size):
        row = bytearray([0])  # filter type: none
        ay = (y - offset) // scale if offset <= y < offset + 16 * scale else None
        for x in range(size):
            ax = (x - offset) // scale if offset <= x < offset + 16 * scale else None
            c = ART[ay][ax] if ay is not None and ax is not None else '.'
            row += bytes(rgb(PALETTE[c]) if c != '.' else bg)
        rows.append(bytes(row))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xFFFFFFFF)

    header = struct.pack('>IIBBBBB', size, size, 8, 2, 0, 0, 0)  # 8-bit RGB
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', header) + chunk(b'IDAT', zlib.compress(b''.join(rows), 9)) + chunk(b'IEND', b'')


if __name__ == '__main__':
    assert all(len(r) == 16 for r in ART) and len(ART) == 16
    (PUBLIC / 'favicon.svg').write_text(favicon())
    for size, name in [(180, 'apple-touch-icon.png'), (192, 'icon-192.png'), (512, 'icon-512.png')]:
        (PUBLIC / name).write_bytes(png(size))
    print('wrote', ', '.join(p.name for p in sorted(PUBLIC.iterdir())))
