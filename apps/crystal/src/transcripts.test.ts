import { mkdirSync, mkdtempSync, rmSync, utimesSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { findTranscript, listTranscripts, transcriptEvents } from './transcripts.js';

// Shapes recorded from Claude Code 2.1.312 transcripts; the text is made up.
const ID = '11111111-1111-4111-8111-111111111111';
// Real folders: a session whose folder no longer exists is left out of the list.
const CWD = tmpdir();
const OTHER = homedir();
const lines = (...objects: object[]) => objects.map((o) => JSON.stringify(o)).join('\n') + '\n';
const user = (content: unknown, extra: object = {}) => ({
  type: 'user',
  cwd: CWD,
  sessionId: ID,
  isSidechain: false,
  timestamp: '2026-10-28T10:00:00Z',
  message: { role: 'user', content },
  ...extra,
});
const assistant = (content: unknown[], extra: object = {}) => ({
  type: 'assistant',
  cwd: CWD,
  sessionId: ID,
  isSidechain: false,
  message: { id: 'msg_1', role: 'assistant', content },
  ...extra,
});

describe('transcripts', () => {
  let root: string;
  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'crystal-transcripts-'));
  });
  afterEach(() => rmSync(root, { recursive: true, force: true }));

  function write(project: string, id: string, body: string, mtimeSec?: number): string {
    mkdirSync(join(root, project), { recursive: true });
    const file = join(root, project, `${id}.jsonl`);
    writeFileSync(file, body);
    if (mtimeSec !== undefined) utimesSync(file, mtimeSec, mtimeSec);
    return file;
  }

  it('lists sessions newest first with id, cwd, title from the first prompt, and last change', async () => {
    write(
      '-home-me-code-thing',
      ID,
      lines(user('Fix the flaky login test\nsecond line'), assistant([{ type: 'text', text: 'On it.' }])),
      2000,
    );
    write('-home-me-other', '22222222-2222-4222-8222-222222222222', lines({ ...user('Older one'), cwd: OTHER }), 1000);

    expect(await listTranscripts(root)).toEqual([
      { id: ID, cwd: CWD, title: 'Fix the flaky login test', updatedAt: 2_000_000, messages: 2 },
      {
        id: '22222222-2222-4222-8222-222222222222',
        cwd: OTHER,
        title: 'Older one',
        updatedAt: 1_000_000,
        messages: 1,
      },
    ]);
  });

  it('skips subagent files, unreadable lines, files without a cwd, and anything over the limit', async () => {
    write('-p', ID, lines(user('Main'), { ...user('Sub'), isSidechain: true }) + 'not json\n', 3000);
    mkdirSync(join(root, '-p', ID), { recursive: true });
    writeFileSync(join(root, '-p', ID, 'agent-x.jsonl'), lines(user('subagent file')));
    write('-q', '33333333-3333-4333-8333-333333333333', lines({ type: 'summary', summary: 'no cwd here' }), 2000);
    write('-r', '44444444-4444-4444-8444-444444444444', lines(user('Old')), 1000);

    const listed = await listTranscripts(root, { limit: 1 });
    expect(listed).toEqual([{ id: ID, cwd: CWD, title: 'Main', updatedAt: 3_000_000, messages: 1 }]);
  });

  it('titles a session by its first real prompt, skipping the wrappers the CLI puts around commands and reminders', async () => {
    write(
      '-p',
      ID,
      lines(
        user(
          '<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>',
        ),
        user(
          '<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>',
        ),
        user('<system-reminder>Some context.</system-reminder>\nRefactor the parser'),
      ),
      1000,
    );
    expect((await listTranscripts(root))[0]?.title).toBe('Refactor the parser');
  });

  it('keeps pasted text as the prompt, and skips wrappers whose tags carry attributes, closing ones included', async () => {
    write(
      '-p',
      ID,
      lines(
        user(
          '<system-reminder kind="x">ctx</system-reminder><pasted_content id="c1">Fix the deploy script\nmore lines</pasted_content id="c1">',
        ),
      ),
      1000,
    );
    expect((await listTranscripts(root))[0]?.title).toBe('Fix the deploy script');
  });

  it('falls back to the command when that is all there is', async () => {
    write('-p', ID, lines(user('<command-name>/usage</command-name>\n<command-message>usage</command-message>')), 1000);
    expect((await listTranscripts(root))[0]?.title).toBe('/usage');
  });

  it('leaves out sessions whose folder no longer exists, since they cannot be resumed there', async () => {
    const gone = join(root, 'deleted-temp-repo');
    write('-gone', ID, lines({ ...user('Old test'), cwd: gone }), 1000);
    expect(await listTranscripts(root)).toEqual([]);
  });

  it('returns nothing when the projects directory does not exist', async () => {
    expect(await listTranscripts(join(root, 'missing'))).toEqual([]);
  });

  it('finds a transcript by session id, and nothing for an id with path tricks', async () => {
    const file = write('-home-me-code-thing', ID, lines(user('hi')));
    expect(await findTranscript(root, ID)).toBe(file);
    expect(await findTranscript(root, '../../etc/passwd')).toBeUndefined();
    expect(await findTranscript(root, '55555555-5555-4555-8555-555555555555')).toBeUndefined();
  });

  it('turns a transcript into events the hub can replay: prompts as user.message, the rest as claude.event', async () => {
    const toolUse = { type: 'tool_use', id: 'toolu_1', name: 'Bash', input: { command: 'ls' } };
    const file = write(
      '-p',
      ID,
      lines(
        user('List the files'),
        assistant([{ type: 'text', text: 'Listing.' }, toolUse]),
        user([{ type: 'tool_result', tool_use_id: 'toolu_1', content: 'a\nb' }]),
        { ...user('subagent noise'), isSidechain: true },
        { type: 'attachment', cwd: CWD },
        user([{ type: 'text', text: 'Thanks' }]),
      ),
    );

    expect(await transcriptEvents(file)).toEqual([
      { type: 'user.message', payload: { text: 'List the files' } },
      {
        type: 'claude.event',
        payload: {
          engine: 'claude',
          raw: { type: 'assistant', message: assistant([{ type: 'text', text: 'Listing.' }, toolUse]).message },
        },
      },
      {
        type: 'claude.event',
        payload: {
          engine: 'claude',
          raw: {
            type: 'user',
            message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: 'toolu_1', content: 'a\nb' }] },
          },
        },
      },
      { type: 'user.message', payload: { text: 'Thanks' } },
    ]);
  });
});
